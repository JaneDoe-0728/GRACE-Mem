#!/usr/bin/env python3
"""
Filter method ablation sweep for locomo10.

Runs RRF, PPR, and RRF+PPR configurations as retrieval-only experiments by
reusing ingest artifacts from a previous run.  Each configuration is launched
as a separate pipeline invocation with a custom experiment_config.py injected
via PYTHONPATH, so neither workers.py nor qa_eval.py need to be modified.

Usage (retrieval-only, reusing baseline ingest artifacts):
    uv run python -m experiment.locomo.analysis.filter_sweep \
        --artifact-dir experiment/locomo/output/standard/oss-20b-0429 \
        [--date-tag 0430]      # suffix appended to run tags (default: today MMDD)
        [--quick]              # 3 canonical configs only (rrf-k60/ppr-a085/rrf+ppr-a085)
        [--only rrf-k60,ppr-a085]  # run specific config labels only
        [--no-judge]           # skip LLM judge (faster, no correctness scores)
        [--dry-run]            # print commands without running

Sweep grid (13 configs):
    RRF:        rrf-k30, rrf-k60, rrf-k120, rrf-k60-top5, rrf-k60-top15
    PPR:        ppr-a05, ppr-a07, ppr-a085, ppr-a085-top5, ppr-a085-top15
    RRF+PPR:    rrf+ppr-a085, rrf+ppr-a07, rrf+ppr-cand30

Outputs:
    experiment/locomo/output/standard/fs-<label>-<date-tag>/   per config
    experiment/locomo/filter_sweep_<date-tag>.json  ranked results
"""
import argparse
import json
import os
import shutil
import subprocess
import tempfile
from datetime import datetime
from pathlib import Path

# ── Repository layout ────────────────────────────────────────────────────────
SCRIPT_DIR = Path(__file__).resolve().parent           # locomo/analysis/
LOCOMO_ROOT = SCRIPT_DIR.parent                        # locomo/
EXPERIMENT_ROOT = LOCOMO_ROOT.parent                   # experiment/
REPO_ROOT = EXPERIMENT_ROOT.parent                     # repo root

# ── Base params mirroring experiment_config.py defaults ─────────────────────
# These are used to build a custom experiment_config.py for each sweep config.
# Update these if experiment_config.py defaults change.

BASE_INGEST_PARAMS = dict(
    ingest_mode="turn_pairs",
    prev_k=2,
    entity_sim_topk=3,
    entity_sim_threshold=0.6,
)

BASE_RETRIEVAL_PARAMS = dict(
    ent_topk=20,
    rel_topk=10,
    ent_threshold=0.2,
    rel_threshold=0.2,
    filter_ent_topk=10,
    filter_rel_topk=10,
    filter_ent_threshold=0.4,
    filter_rel_threshold=0.4,
    summary_topk_per_item=8,
    summary_vec_threshold=0.4,
)

BASE_RERANKER_PARAMS = dict(
    use_reranker=True,
    reranker_threshold=-3.0,
    reranker_topk=5,
    use_spreading_activation=False,
    sa_max_hops=2,
    sa_rescale_c=0.4,
    sa_tau_a=0.5,
    sa_max_activated=20,
    # Filter method (new fields added by RRF/PPR implementation)
    filter_method="similarity",    # baseline: preserves old cosine-threshold behavior
    rrf_k=60.0,
    rrf_candidate_k=50,
    ppr_alpha=0.85,
    ppr_top_k=10,
    ppr_inverse_degree=False,
)

# Keys that belong to RETRIEVAL_PARAMS (call-time args to build_kg_context).
# All other non-underscore keys go into RERANKER_PARAMS (init-time RetrieverConfig).
_RETRIEVAL_KEYS = frozenset({"filter_ent_topk", "filter_rel_topk"})

# ── Sweep grid ───────────────────────────────────────────────────────────────
# Each entry: _label key + overrides for RETRIEVAL_PARAMS or RERANKER_PARAMS.
SWEEP_GRID = [
    {"_label": "rrf-k60-top15",
     "filter_method": "rrf",    "rrf_k": 60.0,
     "filter_ent_topk": 15, "filter_rel_topk": 15},
]

# Labels included in --quick mode
QUICK_LABELS = frozenset({"rrf-k60", "ppr-a085", "rrf+ppr-a085"})


# ── Config generation ────────────────────────────────────────────────────────

def _build_config_module(cfg: dict) -> str:
    """Return the content of a custom experiment_config.py for this sweep config."""
    retrieval = dict(BASE_RETRIEVAL_PARAMS)
    reranker = dict(BASE_RERANKER_PARAMS)
    for k, v in cfg.items():
        if k.startswith("_"):
            continue
        if k in _RETRIEVAL_KEYS:
            retrieval[k] = v
        else:
            reranker[k] = v
    return (
        f"# Auto-generated by run_filter_sweep.py  label={cfg['_label']!r}\n"
        f"INGEST_PARAMS = {BASE_INGEST_PARAMS!r}\n"
        f"RETRIEVAL_PARAMS = {retrieval!r}\n"
        f"RERANKER_PARAMS = {reranker!r}\n"
    )


# ── Run one pipeline invocation ──────────────────────────────────────────────

def _run_config(
    cfg: dict,
    run_tag: str,
    artifact_dir: str,
    no_judge: bool,
    dry_run: bool,
    timeout: int,
    sample_ids: str | None = None,
) -> bool:
    """Launch one pipeline run for cfg.  Returns True on success."""
    config_src = _build_config_module(cfg)

    # Write the custom experiment_config.py into a temp directory.
    # Prepend that directory to PYTHONPATH so both workers.py and qa_eval.py
    # find it before the real experiment_config.py in EXPERIMENT_ROOT.
    tmpdir = tempfile.mkdtemp(prefix=f"kgswp_{cfg['_label']}_")
    try:
        (Path(tmpdir) / "experiment_config.py").write_text(config_src)

        env = os.environ.copy()
        orig_pypath = env.get("PYTHONPATH", "")
        env["PYTHONPATH"] = f"{tmpdir}:{orig_pypath}" if orig_pypath else tmpdir

        cmd = [
            "uv", "run", "python", "-m", "experiment.locomo.pipeline.runner",
            "--dataset", "locomo",
            "--run-tag", run_tag,
            "--artifact-dir", artifact_dir,
        ]
        if no_judge:
            cmd.append("--no-judge")
        if sample_ids:
            cmd.extend(["--sample-ids", sample_ids])

        _sep = "=" * 64
        print(f"\n{_sep}")
        print(f"CONFIG : {cfg['_label']}")
        print(f"RUN TAG: {run_tag}")
        overrides = {k: v for k, v in cfg.items() if not k.startswith("_")}
        print(f"PARAMS : {overrides}")
        print(f"CMD    : {' '.join(cmd)}")
        print(_sep)

        if dry_run:
            print("[dry-run] experiment_config.py would contain:")
            print(config_src)
            return True

        result = subprocess.run(cmd, env=env, cwd=str(REPO_ROOT), timeout=timeout)
        success = result.returncode == 0
        if not success:
            print(f"[WARN] Config '{cfg['_label']}' exited with code {result.returncode}")
        return success

    except subprocess.TimeoutExpired:
        print(f"[ERROR] Config '{cfg['_label']}' timed out after {timeout}s")
        return False
    finally:
        shutil.rmtree(tmpdir, ignore_errors=True)


# ── Results reading ──────────────────────────────────────────────────────────

def _read_aggregate(run_tag: str) -> dict | None:
    agg_path = (
        EXPERIMENT_ROOT / "locomo" / "output" / "standard"
        / run_tag / "_correctness_aggregate.json"
    )
    if not agg_path.exists():
        return None
    try:
        return json.loads(agg_path.read_text())
    except Exception as exc:
        print(f"[WARN] Could not read aggregate for {run_tag}: {exc}")
        return None


def _reward(agg: dict) -> float:
    """Reward signal from program.md: correctness + 0.1*f1 - 0.05*(tokens/1000)."""
    overall = agg.get("overall", {})
    correctness = overall.get("avg_correctness", 0.0)
    f1 = overall.get("avg_f1", 0.0)
    tokens = overall.get("avg_tokens_retrieved", 0.0)
    return correctness + 0.1 * f1 - 0.05 * (tokens / 1000.0)


# ── Results display ──────────────────────────────────────────────────────────

def _print_results_table(results: list) -> None:
    sep = "=" * 96
    print(f"\n{sep}")
    print("FILTER SWEEP RESULTS  (sorted by reward = correctness + 0.1*f1 - 0.05*tokens/1000)")
    print(sep)
    fmt = "{:>4}  {:<24}  {:>11}  {:>6}  {:>6}  {:>10}  {:>8}"
    print(fmt.format("Rank", "Label", "Correctness", "F1", "BLEU1", "Tokens", "Reward"))
    print("-" * 96)

    ranked = sorted(
        [r for r in results if r.get("agg")],
        key=lambda r: _reward(r["agg"]),
        reverse=True,
    )
    failed = [r for r in results if not r.get("agg")]

    for rank, r in enumerate(ranked, 1):
        overall = r["agg"].get("overall", {})
        print(fmt.format(
            rank,
            r["label"],
            f"{overall.get('avg_correctness', 0):.4f}",
            f"{overall.get('avg_f1', 0):.4f}",
            f"{overall.get('avg_bleu1', 0):.4f}",
            f"{overall.get('avg_tokens_retrieved', 0):.0f}",
            f"{_reward(r['agg']):.4f}",
        ))

    for r in failed:
        print(fmt.format("-", r["label"], "FAILED", "-", "-", "-", "-"))

    print(sep)

    if ranked:
        best = ranked[0]
        print(f"\nBEST CONFIG: {best['label']}  (run-tag: {best['run_tag']})")
        params = best["cfg"]
        print(f"  filter_method    = {params.get('filter_method')}")
        for k, v in params.items():
            if k != "filter_method":
                print(f"  {k:<20} = {v}")

    if len(ranked) >= 2:
        print("\nPER-CATEGORY BREAKDOWN (top 3):")
        cat_hdr = f"  {'Label':<24}"
        categories = list(
            (ranked[0]["agg"].get("overall", {}).get("by_category") or {}).keys()
        )
        for cat in categories:
            cat_hdr += f"  {cat[:10]:>10}"
        print(cat_hdr)
        for r in ranked[:3]:
            by_cat = (r["agg"].get("overall") or {}).get("by_category") or {}
            row = f"  {r['label']:<24}"
            for cat in categories:
                row += f"  {by_cat.get(cat, {}).get('avg_correctness', 0):>10.4f}"
            print(row)


# ── Main ─────────────────────────────────────────────────────────────────────

def main() -> None:
    parser = argparse.ArgumentParser(
        description="Filter method ablation sweep for locomo10",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument(
        "--artifact-dir", required=True,
        help="Base run dir to reuse ingest artifacts from "
             "(e.g. experiment/locomo/output/standard/oss-20b-0429)",
    )
    parser.add_argument(
        "--date-tag", default=datetime.now().strftime("%m%d"),
        help="Date suffix appended to run tags (default: today MMDD)",
    )
    parser.add_argument(
        "--quick", action="store_true",
        help="Run only 4 canonical configs: sim, rrf-k60, ppr-a085, rrf+ppr-a085",
    )

    parser.add_argument(
        "--only", default=None,
        help="Comma-separated labels to run (e.g. --only rrf-k60,ppr-a085)",
    )
    parser.add_argument(
        "--no-judge", action="store_true",
        help="Skip LLM judge (faster; correctness scores unavailable)",
    )
    parser.add_argument(
        "--dry-run", action="store_true",
        help="Print commands and generated configs without running",
    )
    parser.add_argument(
        "--timeout", type=int, default=21600,
        help="Per-run timeout in seconds (default: 21600 = 6 h)",
    )
    parser.add_argument(
        "--sample-ids", default=None,
        help="Sample IDs to run (e.g. 0-9, 0,2,5-7); passed through to pipeline",
    )
    args = parser.parse_args()

    # ── Select grid subset ───────────────────────────────────────────────────
    grid = list(SWEEP_GRID)
    if args.quick:
        grid = [c for c in grid if c["_label"] in QUICK_LABELS]

    if args.only:
        only_set = {lbl.strip() for lbl in args.only.split(",")}
        unknown = only_set - {c["_label"] for c in SWEEP_GRID}
        if unknown:
            parser.error(f"Unknown config labels: {sorted(unknown)}")
        grid = [c for c in grid if c["_label"] in only_set]

    if not grid:
        parser.error("No configs selected — check --quick / --skip-baseline / --only.")

    print(f"Filter sweep: {len(grid)} configuration(s)")
    print(f"  artifact-dir : {args.artifact_dir}")
    print(f"  date-tag     : {args.date_tag}")
    print(f"  configs      : {[c['_label'] for c in grid]}")

    # ── Run each config ──────────────────────────────────────────────────────
    results = []
    for cfg in grid:
        label = cfg["_label"]
        run_tag = f"fs-{label}-{args.date_tag}"
        success = _run_config(
            cfg=cfg,
            run_tag=run_tag,
            artifact_dir=args.artifact_dir,
            no_judge=args.no_judge,
            dry_run=args.dry_run,
            timeout=args.timeout,
            sample_ids=args.sample_ids,
        )
        agg = _read_aggregate(run_tag) if (not args.dry_run and success) else None
        results.append({
            "label": label,
            "run_tag": run_tag,
            "cfg": {k: v for k, v in cfg.items() if not k.startswith("_")},
            "success": success,
            "agg": agg,
        })

    # ── Print and save results ───────────────────────────────────────────────
    if args.dry_run:
        print(f"\n[dry-run] Would run {len(grid)} configs.")
        return

    _print_results_table(results)

    out_path = LOCOMO_ROOT / f"filter_sweep_{args.date_tag}.json"
    out_path.write_text(json.dumps(results, indent=2, ensure_ascii=False))
    print(f"\nDetailed results saved to {out_path.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
